/// Capcom "Orbit" menu-bar glyphs (18 pt, @1x + @2x), generated by
/// `packaging/macos/icon/make-icon.sh` and embedded so the bare CLI binary needs no resources.
#[derive(Clone, Copy)]
enum Orbit {
    /// Black-on-transparent template: macOS tints it for light/dark menu bars.
    Idle,
    /// Open orbit, voice quiet (template).
    Processing,
    /// System-red, non-template.
    Listening,
}

impl Orbit {
    fn pngs(self) -> (&'static [u8], &'static [u8], bool) {
        match self {
            Orbit::Idle => (include_bytes!("icons/orbit-template.png"), include_bytes!("icons/orbit-template@2x.png"), true),
            Orbit::Processing => (
                include_bytes!("icons/orbit-processing-template.png"),
                include_bytes!("icons/orbit-processing-template@2x.png"),
                true,
            ),
            Orbit::Listening => (include_bytes!("icons/orbit-listening.png"), include_bytes!("icons/orbit-listening@2x.png"), false),
        }
    }

    /// An 18×18 pt NSImage carrying both bitmap scales.
    fn image(self, desc: &NSString) -> Option<Retained<NSImage>> {
        let (x1, x2, template) = self.pngs();
        let size = NSSize::new(18.0, 18.0);
        let img = NSImage::initWithSize(NSImage::alloc(), size);
        for bytes in [x1, x2] {
            let rep = NSBitmapImageRep::imageRepWithData(&NSData::with_bytes(bytes))?;
            rep.setSize(size);
            img.addRepresentation(&rep);
        }
        img.setTemplate(template);
        img.setAccessibilityDescription(Some(desc));
        Some(img)
    }
}

/// What the status button shows for a state: an Orbit glyph or an SF Symbol (optionally tinted).
enum Icon {
    Orbit(Orbit),
    Symbol(&'static str, Option<Retained<NSColor>>),
}

/// Re-check the server at most this often (on menu open).
const SERVER_CHECK_EVERY: Duration = Duration::from_secs(30);

struct Shared {
    mtm: MainThreadMarker,
    item: Retained<NSStatusItem>,
    header: Retained<NSMenuItem>,
    toggle: Retained<NSMenuItem>,
    last_error: Retained<NSMenuItem>,
    server: Retained<NSMenuItem>,
    mic: Retained<NSMenuItem>,
    mic_menu: Retained<NSMenu>,
    /// `audio.device` value behind each submenu item, by tag (rebuilt together with the items).
    mic_values: RefCell<Vec<String>>,
    login: Retained<NSMenuItem>,
    _menu: Retained<NSMenu>,
    target: Retained<MenuTarget>,
    state: Cell<UiState>,
    cfg: Config,
    bundled: bool,
    last_server_check: Cell<Option<Instant>>,
}

thread_local! {
    static SHARED: RefCell<Option<Rc<Shared>>> = const { RefCell::new(None) };
}

fn with_shared(f: impl FnOnce(&Shared)) {
    if let Some(s) = SHARED.with(|s| s.borrow().clone()) {
        f(&s);
    }
}

/// Drop the status menu down (used when Capcom.app is double-clicked while running).
pub fn pop_menu(_mtm: MainThreadMarker) {
    with_shared(|s| {
        if let Some(b) = s.item.button(s.mtm) {
            // SAFETY: plain action dispatch on a live button.
            unsafe { b.performClick(None) };
        }
    });
}

define_class!(
    // SAFETY: NSObject has no subclassing requirements; MenuTarget does not implement Drop.
    #[unsafe(super = NSObject)]
    #[thread_kind = MainThreadOnly]
    #[name = "CapcomMenuTarget"]
    struct MenuTarget;

    impl MenuTarget {
        #[unsafe(method(toggleDictation:))]
        fn toggle_dictation(&self, _sender: Option<&AnyObject>) {
            background(|| {
                let r = ipc_blocking(&ipc::socket_path(), &Request::Toggle, Duration::from_secs(5));
                match r {
                    Ok(r) if !r.ok => crate::platform::macos::notify(r.error.as_deref().unwrap_or("dictation failed")),
                    Err(e) => crate::platform::macos::notify(&format!("daemon unreachable: {e}")),
                    Ok(_) => {}
                }
            });
        }

        #[unsafe(method(copyLast:))]
        fn copy_last(&self, _sender: Option<&AnyObject>) {
            background(|| match last_transcript() {
                Some(text) => on_main(move || {
                    let pb = NSPasteboard::generalPasteboard();
                    pb.clearContents();
                    // SAFETY: NSPasteboardTypeString is a valid static.
                    pb.setString_forType(&NSString::from_str(&text), unsafe { NSPasteboardTypeString });
                }),
                None => crate::platform::macos::notify("No transcript yet"),
            });
        }

        #[unsafe(method(openConfig:))]
        fn open_config(&self, _sender: Option<&AnyObject>) {
            background(|| {
                let p = config::config_path();
                if !p.exists() {
                    if let Err(e) = config::init(false) {
                        crate::platform::macos::notify(&format!("cannot create config: {e:#}"));
                        return;
                    }
                }
                open_text(&p);
            });
        }

        #[unsafe(method(openSetup:))]
        fn open_setup(&self, _sender: Option<&AnyObject>) {
            background(|| {
                if let Err(e) = open_setup_in_terminal() {
                    crate::platform::macos::notify(&format!("cannot open Terminal: {e:#}; run `capcom setup`"));
                }
            });
        }

        #[unsafe(method(openHistory:))]
        fn open_history(&self, _sender: Option<&AnyObject>) {
            background(|| {
                let p = crate::history::default_path();
                if p.exists() {
                    open_text(&p);
                } else {
                    crate::platform::macos::notify("No history yet");
                }
            });
        }

        #[unsafe(method(pickMic:))]
        fn pick_mic(&self, sender: Option<&AnyObject>) {
            let Some(item) = sender.and_then(|s| s.downcast_ref::<NSMenuItem>()) else { return };
            let tag = item.tag();
            with_shared(|s| s.pick_mic(tag));
        }

        #[unsafe(method(toggleLogin:))]
        fn toggle_login(&self, _sender: Option<&AnyObject>) {
            with_shared(|s| s.toggle_login());
        }

        #[unsafe(method(quit:))]
        fn quit(&self, _sender: Option<&AnyObject>) {
            request_quit();
        }
    }

    unsafe impl NSObjectProtocol for MenuTarget {}

    unsafe impl NSMenuDelegate for MenuTarget {
        #[unsafe(method(menuWillOpen:))]
        fn menu_will_open(&self, _menu: &NSMenu) {
            with_shared(|s| {
                s.refresh_login();
                s.maybe_check_server();
                s.refresh_mic();
            });
        }
    }
);

impl MenuTarget {
    fn new(mtm: MainThreadMarker) -> Retained<Self> {
        let this = Self::alloc(mtm).set_ivars(());
        // SAFETY: NSObject's `init` signature.
        unsafe { msg_send![super(this), init] }
    }
}

/// The menu-bar component. Construct on the main thread, then `UiHost::register` it.
pub struct StatusItem {
    shared: Rc<Shared>,
}

impl StatusItem {
    pub fn new(mtm: MainThreadMarker, cfg: &Config, bundled: bool) -> Self {
        let target = MenuTarget::new(mtm);
        let item = NSStatusBar::systemStatusBar().statusItemWithLength(NSVariableStatusItemLength);
        let menu = NSMenu::new(mtm);
        menu.setAutoenablesItems(false);
        menu.setDelegate(Some(ProtocolObject::from_ref(&*target)));

        let add = |title: &str, action: Option<Sel>| -> Retained<NSMenuItem> {
            // SAFETY: valid title/selector; key equivalent empty.
            let it = unsafe {
                NSMenuItem::initWithTitle_action_keyEquivalent(NSMenuItem::alloc(mtm), &NSString::from_str(title), action, ns_string!(""))
            };
            if action.is_some() {
                // SAFETY: target is retained by `Shared` for the life of the menu.
                unsafe { it.setTarget(Some(&target)) };
            } else {
                it.setEnabled(false);
            }
            menu.addItem(&it);
            it
        };
        let sep = || menu.addItem(&NSMenuItem::separatorItem(mtm));

        let header = add("Capcom — Ready", None);
        add(&hotkey_hint(&cfg.hotkey.push_to_talk), None);
        if cfg.setup_problem().is_some() {
            sep();
            add("Set up Capcom…", Some(sel!(openSetup:)));
        }
        let last_error = add("", None);
        last_error.setHidden(true);
        sep();
        let toggle = add("Start dictation", Some(sel!(toggleDictation:)));
        add("Copy last transcript", Some(sel!(copyLast:)));
        sep();
        add("Open config file", Some(sel!(openConfig:)));
        add("Open history", Some(sel!(openHistory:)));
        let server = add("Server: checking…", None);
        let mic = add("Microphone: …", None);
        let mic_menu = NSMenu::new(mtm);
        mic_menu.setAutoenablesItems(false);
        mic.setSubmenu(Some(&mic_menu));
        mic.setEnabled(true); // `add` disables action-less items; a submenu parent must stay enabled
        sep();
        let login = add("Launch at login", Some(sel!(toggleLogin:)));
        if !bundled {
            login.setTitle(ns_string!("Launch at login (Capcom.app only)"));
            login.setEnabled(false);
        }
        sep();
        add("Quit Capcom", Some(sel!(quit:)));
        item.setMenu(Some(&menu));

        let shared = Rc::new(Shared {
            mtm,
            item,
            header,
            toggle,
            last_error,
            server,
            mic,
            mic_menu,
            mic_values: RefCell::new(Vec::new()),
            login,
            _menu: menu,
            target,
            state: Cell::new(UiState::Idle),
            cfg: cfg.clone(),
            bundled,
            last_server_check: Cell::new(None),
        });
        SHARED.with(|s| *s.borrow_mut() = Some(shared.clone()));
        shared.render(UiState::Idle, None);
        shared.refresh_login();
        shared.maybe_check_server();
        shared.refresh_mic();
        Self { shared }
    }
}

impl UiComponent for StatusItem {
    fn handle(&mut self, ev: &UiEvent) {
        match ev {
            UiEvent::State(st) => {
                self.shared.state.set(*st);
                if *st == UiState::Done {
                    self.shared.last_error.setHidden(true);
                }
                self.shared.render(*st, None);
            }
            UiEvent::Error(m) => {
                let short = truncate(m, 70);
                self.shared.last_error.setTitle(&NSString::from_str(&format!("Last error: {short}")));
                self.shared.last_error.setHidden(false);
                self.shared.render(self.shared.state.get(), Some(m));
            }
            UiEvent::Level(_) => {}
        }
    }
}

impl Shared {
    /// Icon, tint, tooltip, header and toggle label for `state` (with an optional error overlay).
    fn render(&self, state: UiState, error: Option<&str>) {
        let (icon, label) = match (error, state) {
            (Some(_), _) => (Icon::Symbol("exclamationmark.triangle", Some(NSColor::systemOrangeColor())), "Error"),
            (None, UiState::Listening) => (Icon::Orbit(Orbit::Listening), "Listening"),
            (None, UiState::Processing) => (Icon::Orbit(Orbit::Processing), "Processing"),
            (None, UiState::Done) => (Icon::Symbol("checkmark.circle", None), "Done"),
            (None, UiState::Idle | UiState::Cancelled) => (Icon::Orbit(Orbit::Idle), "Ready"),
        };
        let tooltip = match error {
            Some(m) => format!("Capcom — error: {}", truncate(m, 200)),
            None => format!("Capcom — {label}"),
        };
        if let Some(button) = self.item.button(self.mtm) {
            let desc = NSString::from_str(&tooltip);
            let img = match icon {
                Icon::Orbit(orbit) => orbit.image(&desc),
                Icon::Symbol(symbol, tint) => {
                    NSImage::imageWithSystemSymbolName_accessibilityDescription(&NSString::from_str(symbol), Some(&desc)).map(|img| {
                        // Status-bar buttons ignore contentTintColor for template images, so colored
                        // states use a non-template symbol rendered with a palette color.
                        match &tint {
                            Some(color) => {
                                let conf = NSImageSymbolConfiguration::configurationWithPaletteColors(&NSArray::from_retained_slice(
                                    std::slice::from_ref(color),
                                ));
                                let colored = img.imageWithSymbolConfiguration(&conf).unwrap_or(img);
                                colored.setTemplate(false);
                                colored
                            }
                            None => {
                                img.setTemplate(true);
                                img
                            }
                        }
                    })
                }
            };
            match img {
                Some(img) => button.setImage(Some(&img)),
                None => button.setTitle(ns_string!("Capcom")),
            }
            button.setToolTip(Some(&desc));
        }
        self.header.setTitle(&NSString::from_str(&format!("Capcom — {label}")));
        let listening = state == UiState::Listening;
        self.toggle.setTitle(if listening { ns_string!("Stop dictation") } else { ns_string!("Start dictation") });
        self.toggle.setEnabled(state != UiState::Processing);
    }

    fn login_service(&self) -> Option<Retained<SMAppService>> {
        // SAFETY: class method without preconditions (macOS 13+).
        self.bundled.then(|| unsafe { SMAppService::mainAppService() })
    }

    fn refresh_login(&self) {
        let Some(svc) = self.login_service() else { return };
        // SAFETY: plain getter.
        let status = unsafe { svc.status() };
        let (state, title) = match status {
            SMAppServiceStatus::Enabled => (NSControlStateValueOn, "Launch at login"),
            SMAppServiceStatus::RequiresApproval => (NSControlStateValueMixed, "Launch at login (approve in System Settings)"),
            _ => (NSControlStateValueOff, "Launch at login"),
        };
        self.login.setState(state);
        self.login.setTitle(&NSString::from_str(title));
    }

    fn toggle_login(&self) {
        let Some(svc) = self.login_service() else {
            crate::platform::macos::notify("Launch at login only works when Capcom runs as Capcom.app");
            return;
        };
        // SAFETY: SMAppService register/unregister have no preconditions beyond running bundled.
        let res = unsafe {
            if svc.status() == SMAppServiceStatus::Enabled {
                svc.unregisterAndReturnError()
            } else {
                svc.registerAndReturnError()
            }
        };
        if let Err(e) = res {
            crate::platform::macos::notify(&format!("Launch at login: {}", e.localizedDescription()));
        }
        // SAFETY: plain getter / opens System Settings.
        if unsafe { svc.status() } == SMAppServiceStatus::RequiresApproval {
            unsafe { SMAppService::openSystemSettingsLoginItems() };
        }
        self.refresh_login();
    }

    /// Rebuild the Microphone item from the config file and the current input devices. The
    /// enumeration runs off the main thread; the menu keeps its previous items until it lands.
    fn refresh_mic(&self) {
        background(|| {
            let configured = Config::load().map(|c| c.audio.device).unwrap_or_else(|e| {
                tracing::warn!("microphone menu: cannot read config: {e:#}");
                "default".into()
            });
            let devices = list_input_devices().unwrap_or_else(|e| {
                tracing::warn!("microphone menu: cannot list input devices: {e:#}");
                Vec::new()
            });
            let model = mic_menu_model(&configured, &devices);
            on_main(move || with_shared(|s| s.apply_mic(&model)));
        });
    }

    fn apply_mic(&self, model: &MicMenuModel) {
        self.mic.setTitle(&NSString::from_str(&model.title));
        self.mic_menu.removeAllItems();
        let mut values = self.mic_values.borrow_mut();
        values.clear();
        for (i, c) in model.choices.iter().enumerate() {
            // SAFETY: valid title/selector; key equivalent empty.
            let it = unsafe {
                NSMenuItem::initWithTitle_action_keyEquivalent(
                    NSMenuItem::alloc(self.mtm),
                    &NSString::from_str(&c.title),
                    Some(sel!(pickMic:)),
                    ns_string!(""),
                )
            };
            // SAFETY: the target is retained by `Shared` for the life of the menu.
            unsafe { it.setTarget(Some(&self.target)) };
            it.setTag(i as isize);
            it.setEnabled(c.available);
            it.setState(if c.checked { NSControlStateValueOn } else { NSControlStateValueOff });
            self.mic_menu.addItem(&it);
            values.push(c.value.clone());
        }
    }

    /// Save the choice to the config, then tell the daemon (it applies it from the next recording).
    fn pick_mic(&self, tag: isize) {
        let Some(value) = usize::try_from(tag).ok().and_then(|i| self.mic_values.borrow().get(i).cloned()) else { return };
        background(move || {
            if let Err(e) = config::save_audio_device(&config::config_path(), &value) {
                crate::platform::macos::notify(&format!("cannot save microphone: {e:#}"));
                return;
            }
            let r = ipc_blocking(&ipc::socket_path(), &Request::SetDevice { name: value }, Duration::from_secs(5));
            match r {
                Ok(r) if !r.ok => crate::platform::macos::notify(r.error.as_deref().unwrap_or("cannot switch microphone")),
                Err(e) => crate::platform::macos::notify(&format!("daemon unreachable: {e}")),
                Ok(_) => {}
            }
            on_main(|| with_shared(|s| s.refresh_mic()));
        });
    }

    fn maybe_check_server(&self) {
        if self.last_server_check.get().is_some_and(|t| t.elapsed() < SERVER_CHECK_EVERY) {
            return;
        }
        self.last_server_check.set(Some(Instant::now()));
        let (asr, llm, key) = (self.cfg.server.asr_url.clone(), self.cfg.server.llm_url.clone(), self.cfg.api_key().ok().flatten());
        let bundled = self.bundled;
        background(move || {
            let mut line = check_server(&asr, &llm, key.as_deref());
            if bundled && line.contains("unreachable") {
                // A bundled app needs macOS "Local Network" permission to reach a LAN server.
                line.push_str(" (Local Network allowed?)");
            }
            on_main(move || with_shared(|s| s.server.setTitle(&NSString::from_str(&line))));
        });
    }
}

/// One entry of the Microphone submenu.
#[derive(Debug, PartialEq)]
struct MicChoice {
    title: String,
    /// What gets written to `[audio] device`.
    value: String,
    checked: bool,
    /// False for a configured device that is not plugged in.
    available: bool,
}

#[derive(Debug, PartialEq)]
struct MicMenuModel {
    /// The menu line, e.g. `Microphone: MacBook Pro Microphone`.
    title: String,
    choices: Vec<MicChoice>,
}

/// Labels and checkmarks for the Microphone submenu: "System default (<name>)" first, then every
/// input device. The device `configured` resolves to is checked (same matching as recording);
/// a configured device that is gone is listed, checked and unavailable.
fn mic_menu_model(configured: &str, devices: &[DeviceInfo]) -> MicMenuModel {
    let names: Vec<&str> = devices.iter().map(|d| d.name.as_str()).collect();
    let default_name = devices.iter().find(|d| d.is_default).map(|d| d.name.as_str());
    let is_default = is_default_choice(configured);
    let matched = pick_device_name(configured, &names);
    let missing = !is_default && matched.is_none();

    let mut choices = vec![MicChoice {
        title: format!("System default ({})", default_name.unwrap_or("no input device")),
        value: "default".into(),
        checked: is_default,
        available: true,
    }];
    if missing {
        choices.push(MicChoice {
            title: format!("{} (not connected)", configured.trim()),
            value: configured.trim().into(),
            checked: true,
            available: false,
        });
    }
    for (i, d) in devices.iter().enumerate() {
        choices.push(MicChoice { title: d.name.clone(), value: d.name.clone(), checked: matched == Some(i), available: true });
    }
    let title = if missing {
        format!("Microphone: {} (not connected)", configured.trim())
    } else {
        let name = matched.map(|i| names[i]).or(default_name).unwrap_or("no input device");
        format!("Microphone: {name}")
    };
    MicMenuModel { title: truncate(&title, 60), choices }
}

/// Run blocking work off the main thread.
fn background(f: impl FnOnce() + Send + 'static) {
    if let Err(e) = std::thread::Builder::new().name("capcom-menu".into()).spawn(f) {
        tracing::warn!("cannot spawn menu helper thread: {e}");
    }
}

fn open_text(p: &std::path::Path) {
    match Command::new("open").arg("-t").arg(p).status() {
        Ok(s) if s.success() => {}
        _ => crate::platform::macos::notify(&format!("cannot open {}", p.display())),
    }
}

/// Open Terminal running `<this binary> setup` (via a throwaway `.command` file).
fn open_setup_in_terminal() -> anyhow::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    let exe = std::env::current_exe()?;
    let script = std::env::temp_dir().join("capcom-setup.command");
    let quoted = exe.display().to_string().replace('\'', "'\\''");
    let body = format!("#!/bin/sh\nclear\n'{quoted}' setup\necho\necho 'Then: Quit Capcom from the menu bar and open it again.'\n");
    std::fs::write(&script, body)?;
    std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o700))?;
    let ok = Command::new("open").arg("-a").arg("Terminal").arg(&script).status()?.success();
    anyhow::ensure!(ok, "`open` failed");
    Ok(())
}

/// Last transcript from the daemon (in-memory last result, then history).
fn last_transcript() -> Option<String> {
    let sock = ipc::socket_path();
    let t = Duration::from_secs(3);
    let from_status = ipc_blocking(&sock, &Request::Status, t)
        .ok()
        .and_then(|r| r.data)
        .and_then(|d| d["last"]["final_text"].as_str().map(String::from));
    let text = from_status.filter(|s| !s.is_empty()).or_else(|| {
        ipc_blocking(&sock, &Request::History { n: 1 }, t)
            .ok()
            .and_then(|r| r.data)
            .and_then(|d| d[0]["final_text"].as_str().map(String::from))
    });
    text.filter(|s| !s.is_empty())
}

/// GET `<base>/v1/models` on both servers with the API key (3 s timeout) -> one menu line.
fn check_server(asr_url: &str, llm_url: &str, key: Option<&str>) -> String {
    let rt = match tokio::runtime::Builder::new_current_thread().enable_all().build() {
        Ok(rt) => rt,
        Err(e) => return format!("Server: check failed ({e})"),
    };
    rt.block_on(async {
        let http = crate::asr::http_client();
        let probe = |url: String| {
            let http = http.clone();
            let key = key.map(String::from);
            async move {
                let t = Instant::now();
                let mut req = http.get(&url).timeout(Duration::from_secs(3));
                if let Some(k) = key {
                    req = req.bearer_auth(k);
                }
                // Any answer that got past auth means "up" (the ASR server has no /v1/models: 404).
                match req.send().await {
                    Ok(r) => match r.status().as_u16() {
                        401 | 403 => Err("key rejected".to_string()),
                        c if c >= 500 => Err(format!("HTTP {c}")),
                        _ => Ok(t.elapsed().as_millis()),
                    },
                    Err(_) => Err("unreachable".to_string()),
                }
            }
        };
        let (a, l) = tokio::join!(probe(models_url(asr_url)), probe(models_url(llm_url)));
        server_line(a, l)
    })
}

fn server_line(asr: Result<u128, String>, llm: Result<u128, String>) -> String {
    match (asr, llm) {
        (Ok(a), Ok(l)) => format!("Server: OK (ASR {a} ms · LLM {l} ms)"),
        (Err(a), Err(l)) if a == l => format!("Server: {a}"),
        (a, l) => {
            let part = |name: &str, r: Result<u128, String>| match r {
                Ok(_) => format!("{name} OK"),
                Err(e) => format!("{name} {e}"),
            };
            format!("Server: {} · {}", part("ASR", a), part("LLM", l))
        }
    }
}

/// `http://h:8001/v1/audio/transcriptions` -> `http://h:8001/v1/models`.
fn models_url(url: &str) -> String {
    if let Some(i) = url.find("/v1/") {
        return format!("{}/v1/models", &url[..i]);
    }
    let scheme_end = url.find("://").map(|i| i + 3).unwrap_or(0);
    let host_end = url[scheme_end..].find('/').map(|i| scheme_end + i).unwrap_or(url.len());
    format!("{}/v1/models", &url[..host_end])
}

/// "Hold right ⌃ to talk · double-tap for hands-free" for a handy-keys trigger name.
fn hotkey_hint(trigger: &str) -> String {
    let t = trigger.trim().to_ascii_lowercase();
    let key = match t.as_str() {
        "ctrlright" | "controlright" | "rightctrl" | "rightcontrol" => "right ⌃".into(),
        "ctrlleft" | "controlleft" | "ctrl" | "control" => "⌃".into(),
        "optright" | "optionright" | "altright" => "right ⌥".into(),
        "optleft" | "optionleft" | "opt" | "option" | "alt" | "altleft" => "⌥".into(),
        "cmdright" | "commandright" | "metaright" => "right ⌘".into(),
        "cmdleft" | "commandleft" | "cmd" | "command" | "meta" => "⌘".into(),
        "shiftright" => "right ⇧".into(),
        "shiftleft" | "shift" => "⇧".into(),
        "fn" | "globe" => "fn".into(),
        _ => trigger.to_string(),
    };
    format!("Hold {key} to talk · double-tap for hands-free")
}

fn truncate(s: &str, max: usize) -> String {
    let s = s.trim();
    if s.chars().count() <= max {
        s.to_string()
    } else {
        format!("{}…", s.chars().take(max.saturating_sub(1)).collect::<String>())
    }
}

